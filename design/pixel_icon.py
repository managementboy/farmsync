#!/usr/bin/env python3
"""Generates Farm Sync's own pixel-art app icon (32x32 grid) as SVG.

Original artwork, built from geometric shapes rasterised onto a pixel grid:
a sprout on a soil mound, framed by two gold sync arrows, over sky and hills.
Nothing is copied from any game. Foreground stays inside the Android adaptive-icon
safe zone (centre circle, ~61 % of the canvas).
Usage: python3 -I design/pixel_icon.py
"""
import math
from pathlib import Path

N = 32
C0 = N / 2  # centre
COL = {
    ".": "#CDEFF7", "c": "#EAF9FC",            # sky, cloud
    "h": "#A6DC88", "H": "#77C463",            # hills
    "g": "#F4C04A", "G": "#D9962A",            # gold, gold shade
    "l": "#86D16A", "L": "#3F9E4B", "k": "#2E7D32",  # leaf light, leaf dark, stem
    "d": "#8A5A33", "D": "#5E3A1E",            # soil
}
grid = [["." for _ in range(N)] for _ in range(N)]


def put(x, y, ch):
    if 0 <= x < N and 0 <= y < N:
        grid[y][x] = ch


def fill(test, ch):
    for y in range(N):
        for x in range(N):
            if test(x + 0.5, y + 0.5):
                put(x, y, ch)


def tri(a, b, c):
    def inside(px, py):
        def s(p1, p2):
            return (px - p2[0]) * (p1[1] - p2[1]) - (p1[0] - p2[0]) * (py - p2[1])
        d1, d2, d3 = s(a, b), s(b, c), s(c, a)
        return not ((d1 < 0 or d2 < 0 or d3 < 0) and (d1 > 0 or d2 > 0 or d3 > 0))
    return inside


def ellipse(cx, cy, rx, ry, rot_deg=0):
    r = math.radians(rot_deg)
    def inside(px, py):
        dx, dy = px - cx, py - cy
        u = dx * math.cos(r) + dy * math.sin(r)
        v = -dx * math.sin(r) + dy * math.cos(r)
        return (u / rx) ** 2 + (v / ry) ** 2 <= 1
    return inside


# Sky details and hills (background layer, full bleed)
fill(ellipse(7, 7, 3.2, 1.3), "c")
fill(ellipse(25, 9, 2.8, 1.1), "c")
fill(lambda x, y: y > 23 + 1.6 * math.sin(x / 4.2), "h")
fill(lambda x, y: y > 27 + 1.2 * math.sin(x / 3.1 + 1), "H")

# Sync ring: radius 9..11 around the centre, two gaps (upper right, lower left)
R_IN, R_OUT = 8.6, 10.8


def ring(px, py):
    d = math.hypot(px - C0, py - C0)
    a = (math.degrees(math.atan2(C0 - py, px - C0)) + 360) % 360  # 0 = right, ccw
    return R_IN <= d <= R_OUT and not (0 <= a <= 44 or 180 <= a <= 224)


fill(ring, "g")
# shade the outer edge on the lower half for a little depth
fill(lambda x, y: ring(x, y) and math.hypot(x - C0, y - C0) > 10.0 and y > C0, "G")


def arrowhead(theta_deg):
    """Arrowhead at angle theta on the ring, pointing clockwise (on screen)."""
    t = math.radians(theta_deg)
    r = (R_IN + R_OUT) / 2
    p = (C0 + r * math.cos(t), C0 - r * math.sin(t))
    tang = (math.sin(t), math.cos(t))      # clockwise direction on screen
    norm = (math.cos(t), -math.sin(t))     # outward
    tip = (p[0] + tang[0] * 5.4, p[1] + tang[1] * 5.4)
    b1 = (p[0] + norm[0] * 4.2, p[1] + norm[1] * 4.2)
    b2 = (p[0] - norm[0] * 4.2, p[1] - norm[1] * 4.2)
    return tri(tip, b1, b2)


fill(arrowhead(50), "g")   # end of the upper arc, pointing into the upper-right gap
fill(arrowhead(230), "g")  # end of the lower arc, pointing into the lower-left gap

# Sprout (foreground)
fill(ellipse(16, 21.6, 6.2, 2.0), "d")
fill(lambda x, y: ellipse(16, 21.6, 6.2, 2.0)(x, y) and y > 22.2, "D")
fill(lambda x, y: 15.0 <= x <= 17.0 and 13.5 <= y <= 21.0, "k")
fill(ellipse(11.6, 15.4, 4.2, 2.1, rot_deg=25), "L")
fill(ellipse(20.2, 12.2, 4.8, 2.4, rot_deg=-28), "l")


def svg(color, title):
    body = "".join(
        f'<rect x="{x}" y="{y}" width="1.02" height="1.02" fill="{color(ch)}"/>'
        for y, row in enumerate(grid) for x, ch in enumerate(row))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {N} {N}" width="512" height="512" '
            f'shape-rendering="crispEdges"><title>{title}</title>{body}</svg>\n')




def vector_xml(cells, comment):
    """Android vector drawable: one <path> per colour, horizontal pixel runs merged."""
    by_color = {}
    for y, row in enumerate(cells):
        x = 0
        while x < N:
            color = row[x]
            if color is None:
                x += 1
                continue
            start = x
            while x < N and row[x] == color:
                x += 1
            by_color.setdefault(color, []).append(f"M{start},{y}h{x - start}v1h{start - x}z")
    paths = "".join(
        f'\n    <path android:fillColor="{c}" android:pathData="{"".join(runs)}"/>' for c, runs in by_color.items())
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} Generated by design/pixel_icon.py -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="108dp" android:height="108dp"\n'
            f'    android:viewportWidth="{N}" android:viewportHeight="{N}">{paths}\n</vector>\n')


def write_android(res_dir, colour_grid, mono_grid):
    bg_keys, fg_keys = set(".chH"), set("gGlLkdD")
    bg = [[COL[ch] if ch in bg_keys else COL["h"] for ch in row] for row in colour_grid]
    fg = [[COL[ch] if ch in fg_keys else None for ch in row] for row in colour_grid]
    mono = [["#FFFFFFFF" if ch in fg_keys else None for ch in row] for row in mono_grid]
    d = Path(res_dir) / "drawable"
    d.mkdir(parents=True, exist_ok=True)
    (d / "ic_launcher_background.xml").write_text(vector_xml(bg, "Farm Sync icon background (own pixel art)."))
    (d / "ic_launcher_foreground.xml").write_text(vector_xml(fg, "Farm Sync icon foreground (own pixel art)."))
    (d / "ic_launcher_monochrome.xml").write_text(vector_xml(mono, "Farm Sync themed icon (own pixel art)."))

out = Path(__file__).resolve().parent / "icon"
out.mkdir(exist_ok=True)
(out / "ic_launcher_pixel.svg").write_text(svg(lambda ch: COL[ch], "Farm Sync pixel icon"))
colour_grid = [row[:] for row in grid]
# Monochrome (themed icon): one colour, so keep a 1-pixel gap between ring and sprout
sprout = set("lLkdD")
mono = [row[:] for row in grid]
for y in range(N):
    for x in range(N):
        if grid[y][x] in "gG" and any(
            0 <= x + dx < N and 0 <= y + dy < N and grid[y + dy][x + dx] in sprout
            for dx in (-1, 0, 1) for dy in (-1, 0, 1)):
            mono[y][x] = "."
grid[:] = mono
fg = set("gGlLkdD")
(out / "ic_launcher_pixel_mono.svg").write_text(
    svg(lambda ch: "#CDE8C4" if ch in fg else "#2B3A2E", "Farm Sync pixel icon, monochrome"))
print("written", out)
res = Path(__file__).resolve().parent.parent / "farmsync" / "app" / "src" / "main" / "res"
write_android(res, colour_grid, grid)
print("android layers written to", res / "drawable")
